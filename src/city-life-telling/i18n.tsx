export type Strings = typeof STRINGS.it
export const STR: Record<UiLang, Strings> = STRINGS as unknown as Record<UiLang, Strings>

const LANG_KEY = 'city-life-telling.ui-lang'

export function loadUiLang(storage?: Pick<Storage, 'getItem'> | null): UiLang {
  try {
    const saved = storage?.getItem(LANG_KEY)
    return saved === 'en' || saved === 'it' ? saved : 'it'
  } catch {
    return 'it'
  }
}

export function storeUiLang(lang: UiLang, storage?: Pick<Storage, 'setItem'> | null): void {
  try {
    storage?.setItem(LANG_KEY, lang)
  } catch {
    // ignore
  }
  if (typeof document !== 'undefined') document.documentElement.lang = lang
}

export function statusWord(t: Strings, status: string): string {
  switch (status) {
    case 'irregular': return t.statusIrregular
    case 'delayed': return t.statusDelayed
    case 'disrupted': return t.statusDisrupted
    case 'suspended': return t.statusSuspended
    default: return t.statusNominal
  }
}

